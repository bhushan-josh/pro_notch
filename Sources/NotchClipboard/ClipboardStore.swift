import AppKit
import ImageIO
import NotchCore
import Observation
import UniformTypeIdentifiers

/// Records what the user copies. NSPasteboard posts no change notification, so a slow timer compares
/// `changeCount` and reads the contents only when it moved.
@MainActor
@Observable
final class ClipboardStore {
    private(set) var items: [ClipboardItem] = []

    @ObservationIgnored var onCapture: ((ClipboardItem) -> Void)?

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var ownChangeCount = -1
    @ObservationIgnored private var persists = Defaults[ClipboardSettings.persist]
    @ObservationIgnored private var didLoad = false
    @ObservationIgnored private var saveTask: Task<Void, Never>?
    @ObservationIgnored private var thumbnailCache: [UUID: NSImage] = [:]
    @ObservationIgnored private var iconCache: [String: NSImage] = [:]

    nonisolated static let maxPayloadBytes = 5 * 1024 * 1024
    nonisolated private static let maxTextLength = 1_000_000
    nonisolated private static let maxImageSourceBytes = 64 * 1024 * 1024
    /// Markers password managers and other apps use to ask clipboard tools not to record an item (nspasteboard.org).
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// Still under the app's old name so saved history survives the rename.
    nonisolated static let directory = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        .appendingPathComponent("Dynamic Notch/Clipboard", isDirectory: true)
    nonisolated private static let indexURL = directory.appendingPathComponent("history.json")
    private let io = DispatchQueue(label: "ProNotch.clipboard.io", qos: .utility)

    func start() {
        loadIfNeeded()
        guard timer == nil else { return }
        // Whatever is on the pasteboard now was copied while we were not watching; its source is unknown.
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: Capture

    private func tick() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ownChangeCount else { return }
        capture(from: pasteboard)
    }

    private func capture(from pasteboard: NSPasteboard) {
        guard let types = pasteboard.types, !types.isEmpty else { return }
        guard !types.contains(where: { Self.privateTypes.contains($0.rawValue) }) else { return }
        if let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           Defaults[ClipboardSettings.ignoredApps].contains(source) { return }

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            add(ClipboardItem(kind: .file, preview: ClipboardItem.preview(forFiles: urls), filePaths: paths, signature: "f:" + ClipboardItem.hash(paths.joined(separator: "\n"))))
            return
        }

        if let string = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.utf16.count <= Self.maxTextLength else { return }
            if let url = ClipboardItem.webURL(from: string) {
                add(ClipboardItem(kind: .url, preview: ClipboardItem.preview(for: url), text: url.absoluteString, signature: "u:" + url.absoluteString))
                return
            }
            let preview = ClipboardItem.preview(forText: string)
            // Rich and plain copies of the same text share a signature so they collapse into one row.
            let signature = "t:" + ClipboardItem.hash(string)
            if types.contains(.rtf), let rtf = pasteboard.data(forType: .rtf), rtf.count <= Self.maxPayloadBytes {
                add(ClipboardItem(kind: .richText, preview: preview, text: string, dataType: NSPasteboard.PasteboardType.rtf.rawValue, signature: signature, data: rtf))
            } else {
                add(ClipboardItem(kind: .text, preview: preview, text: string, signature: signature))
            }
            return
        }

        let imageType: NSPasteboard.PasteboardType? = types.contains(.png) ? .png : types.contains(.tiff) ? .tiff : nil
        guard let imageType, let data = pasteboard.data(forType: imageType), data.count <= Self.maxImageSourceBytes else { return }
        let date = Date()
        Task.detached(priority: .utility) { [weak self] in
            guard let item = Self.makeImageItem(data: data, type: imageType, date: date) else { return }
            await self?.add(item)
        }
    }

    /// Hashing, thumbnailing and any TIFF to PNG conversion run off the main thread.
    nonisolated private static func makeImageItem(data: Data, type: NSPasteboard.PasteboardType, date: Date) -> ClipboardItem? {
        var payload = data
        var payloadType = type
        if payload.count > maxPayloadBytes {
            guard type == .tiff, let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]),
                  png.count <= maxPayloadBytes else { return nil }
            payload = png
            payloadType = .png
        }
        guard let source = CGImageSourceCreateWithData(payload as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 96,
        ]
        guard let thumb = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary),
              let thumbPNG = NSBitmapImageRep(cgImage: thumb).representation(using: .png, properties: [:]) else { return nil }
        let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
        let width = properties?[kCGImagePropertyPixelWidth] as? Int ?? thumb.width
        let height = properties?[kCGImagePropertyPixelHeight] as? Int ?? thumb.height
        return ClipboardItem(
            kind: .image,
            preview: "Image \(width) × \(height)",
            dataType: payloadType.rawValue,
            signature: "i:" + ClipboardItem.hash(payload),
            data: payload,
            thumbnailPNG: thumbPNG,
            date: date
        )
    }

    private func add(_ item: ClipboardItem) {
        if let index = items.firstIndex(where: { $0.signature == item.signature }) {
            items[index].date = max(items[index].date, item.date)
            if items[index].data == nil { items[index].data = item.data }
            if !items[index].isPinned {
                let existing = items.remove(at: index)
                insertByDate(existing)
            }
        } else {
            insertByDate(item)
            writePayload(of: item)
            trim()
        }
        scheduleSave()
        onCapture?(item)
    }

    /// Pinned items stay on top; the rest are newest first.
    private func insertByDate(_ item: ClipboardItem) {
        let index = items.firstIndex { !$0.isPinned && $0.date <= item.date } ?? items.count
        items.insert(item, at: index)
    }

    func trim() {
        let limit = max(1, Defaults[ClipboardSettings.maxItems])
        var unpinned = 0
        var kept: [ClipboardItem] = []
        var evicted: [ClipboardItem] = []
        for item in items {
            if !item.isPinned { unpinned += 1 }
            if !item.isPinned && unpinned > limit { evicted.append(item) } else { kept.append(item) }
        }
        guard !evicted.isEmpty else { return }
        items = kept
        evicted.forEach(forget)
        scheduleSave()
    }

    // MARK: Actions

    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .richText:
            if let rtf = payload(for: item) { pasteboard.setData(rtf, forType: .rtf) }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .url:
            if let url = item.url { pasteboard.writeObjects([url as NSURL]) }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .file:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        case .image:
            if let data = payload(for: item), let type = item.dataType {
                pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
        }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = ownChangeCount
    }

    func itemProvider(for item: ClipboardItem) -> NSItemProvider {
        switch item.kind {
        case .text:
            return NSItemProvider(object: (item.text ?? "") as NSString)
        case .richText:
            let provider = NSItemProvider(object: (item.text ?? "") as NSString)
            if let rtf = payload(for: item) {
                provider.registerDataRepresentation(forTypeIdentifier: UTType.rtf.identifier, visibility: .all) { completion in
                    completion(rtf, nil)
                    return nil
                }
            }
            return provider
        case .url:
            guard let url = item.url else { return NSItemProvider() }
            return NSItemProvider(object: url as NSURL)
        case .file:
            guard let url = item.fileURLs.first else { return NSItemProvider() }
            return NSItemProvider(contentsOf: url) ?? NSItemProvider(object: url as NSURL)
        case .image:
            guard let data = payload(for: item), let type = item.dataType else { return NSItemProvider() }
            return NSItemProvider(item: data as NSData, typeIdentifier: type)
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var changed = items.remove(at: index)
        changed.isPinned.toggle()
        if changed.isPinned {
            items.insert(changed, at: 0)
        } else {
            insertByDate(changed)
            trim()
        }
        scheduleSave()
    }

    func delete(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        forget(items.remove(at: index))
        scheduleSave()
    }

    func clear(keepingPinned: Bool) {
        let removed = keepingPinned ? items.filter { !$0.isPinned } : items
        items = keepingPinned ? items.filter(\.isPinned) : []
        removed.forEach(forget)
        if items.isEmpty {
            saveTask?.cancel()
            let directory = Self.directory
            io.async { try? FileManager.default.removeItem(at: directory) }
        } else {
            scheduleSave()
        }
    }

    // MARK: Display helpers

    func thumbnail(for item: ClipboardItem) -> NSImage? {
        if let cached = thumbnailCache[item.id] { return cached }
        guard let png = item.thumbnailPNG, let image = NSImage(data: png) else { return nil }
        thumbnailCache[item.id] = image
        return image
    }

    func fileIcon(for item: ClipboardItem) -> NSImage {
        let path = item.filePaths?.first ?? ""
        if let cached = iconCache[path] { return cached }
        if iconCache.count >= 64 { iconCache.removeAll() }
        let icon = FileManager.default.fileExists(atPath: path)
            ? NSWorkspace.shared.icon(forFile: path)
            : NSWorkspace.shared.icon(for: UTType(filenameExtension: (path as NSString).pathExtension) ?? .data)
        iconCache[path] = icon
        return icon
    }

    // MARK: Persistence

    /// Items loaded from disk keep their payload there until it is needed.
    private func payload(for item: ClipboardItem) -> Data? {
        if let data = item.data { return data }
        guard item.dataType != nil else { return nil }
        return try? Data(contentsOf: Self.dataURL(item.id))
    }

    nonisolated private static func dataURL(_ id: UUID) -> URL { directory.appendingPathComponent(id.uuidString + ".data") }
    nonisolated private static func thumbnailURL(_ id: UUID) -> URL { directory.appendingPathComponent(id.uuidString + ".thumb.png") }

    private func forget(_ item: ClipboardItem) {
        thumbnailCache[item.id] = nil
        guard item.dataType != nil || item.thumbnailPNG != nil else { return }
        let id = item.id
        io.async {
            try? FileManager.default.removeItem(at: Self.dataURL(id))
            try? FileManager.default.removeItem(at: Self.thumbnailURL(id))
        }
    }

    private func writePayload(of item: ClipboardItem) {
        guard persists, item.data != nil || item.thumbnailPNG != nil else { return }
        let id = item.id
        let data = item.data
        let thumbnail = item.thumbnailPNG
        io.async {
            guard Self.prepareDirectory() else { return }
            if let data { try? data.write(to: Self.dataURL(id), options: .atomic) }
            if let thumbnail { try? thumbnail.write(to: Self.thumbnailURL(id), options: .atomic) }
        }
    }

    /// Coalesces bursts of changes into one index write.
    private func scheduleSave() {
        guard persists else { return }
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1))
            guard !Task.isCancelled else { return }
            self?.saveIndex()
        }
    }

    private func saveIndex() {
        guard persists, let index = try? JSONEncoder().encode(items) else { return }
        io.async {
            guard Self.prepareDirectory() else { return }
            try? index.write(to: Self.indexURL, options: .atomic)
        }
    }

    /// Owner-only and kept out of backups, since the history can hold anything the user copied.
    nonisolated private static func prepareDirectory() -> Bool {
        let manager = FileManager.default
        if manager.fileExists(atPath: directory.path) { return true }
        do {
            try manager.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            var url = directory
            var values = URLResourceValues()
            values.isExcludedFromBackup = true
            try? url.setResourceValues(values)
            return true
        } catch {
            return false
        }
    }

    private func loadIfNeeded() {
        guard !didLoad else { return }
        didLoad = true
        guard persists else { return }
        io.async { [weak self] in
            guard let index = try? Data(contentsOf: Self.indexURL) else { return }
            let names = Set((try? FileManager.default.contentsOfDirectory(atPath: Self.directory.path)) ?? [])
            var thumbnails: [UUID: Data] = [:]
            for name in names where name.hasSuffix(".thumb.png") {
                guard let id = UUID(uuidString: String(name.dropLast(".thumb.png".count))) else { continue }
                thumbnails[id] = try? Data(contentsOf: Self.directory.appendingPathComponent(name))
            }
            DispatchQueue.main.async {
                MainActor.assumeIsolated { self?.merge(index: index, files: names, thumbnails: thumbnails) }
            }
        }
    }

    private func merge(index: Data, files: Set<String>, thumbnails: [UUID: Data]) {
        guard let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: index) else { return }
        var loaded: [ClipboardItem] = []
        for var item in decoded {
            if items.contains(where: { $0.signature == item.signature }) {
                forget(item)
                continue
            }
            item.thumbnailPNG = thumbnails[item.id]
            if item.dataType != nil, !files.contains(item.id.uuidString + ".data") {
                guard item.kind == .richText else { continue }
                item.kind = .text
                item.dataType = nil
            }
            loaded.append(item)
        }
        let captured = items
        items = loaded.filter(\.isPinned) + captured.filter(\.isPinned)
        for item in (loaded + captured).filter({ !$0.isPinned }).sorted(by: { $0.date > $1.date }) {
            items.append(item)
        }
        trim()
    }

    /// Called when `clipboard.persist` changes: writes everything out, or pulls payloads into memory and deletes the files.
    func persistenceChanged() {
        let enabled = Defaults[ClipboardSettings.persist]
        guard enabled != persists else { return }
        if enabled {
            persists = true
            items.forEach(writePayload)
            saveIndex()
        } else {
            for index in items.indices where items[index].data == nil && items[index].dataType != nil {
                items[index].data = payload(for: items[index])
            }
            persists = false
            saveTask?.cancel()
            let directory = Self.directory
            io.async { try? FileManager.default.removeItem(at: directory) }
        }
    }
}
